 id INT AUTO_INCREMENT PRIMARY KEY,
 farm_id INT NOT NULL,
 previous_crop_id INT,
 current_crop_id INT NOT NULL,
 next_crop_id INT,
 plan_code VARCHAR(40) NOT NULL UNIQUE,
 plot_label VARCHAR(80),
 start_date DATE NOT NULL,
 end_date DATE,
 cycle_year SMALLINT UNSIGNED,
 season ENUM('Kharif','Rabi','Zaid','Perennial') NOT NULL,
 objective VARCHAR(150),
 nitrogen_management TEXT,
 pest_objective TEXT,
 cover_crop_notes TEXT,
 traditional_practice TEXT,
 soil_observations TEXT,
 status ENUM('planned','active','completed','cancelled') NOT NULL DEFAULT 'planned',
 residue_management TEXT,
 fallow_days SMALLINT UNSIGNED,
 weed_pressure_notes TEXT,
 water_budget_mm DECIMAL(8,2) CHECK (water_budget_mm >= 0),
 review_on DATE,
 review_notes TEXT,
